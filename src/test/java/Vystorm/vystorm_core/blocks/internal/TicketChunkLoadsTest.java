package Vystorm.vystorm_core.blocks.internal;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import Vystorm.vystorm_core.blocks.ChunkHold;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.NoSuchElementException;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.CancellationException;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CompletionException;
import org.bukkit.Chunk;
import org.bukkit.World;
import org.bukkit.plugin.Plugin;
import org.junit.jupiter.api.Test;

class TicketChunkLoadsTest {
    private static long key(int x, int z) { return ((long) x << 32) | (z & 0xFFFFFFFFL); }

    /** Fake server: chunks loaded or generated by coordinate, async futures completed by the test, tickets counted. */
    static final class FakeSource implements TicketChunkLoads.ChunkSource {
        final boolean async;
        final FakeHost host;
        final Set<Long> loaded = new HashSet<>(), generated = new HashSet<>();
        final Map<Long, Integer> ticketsAdded = new HashMap<>(), ticketsRemoved = new HashMap<>();
        final List<CompletableFuture<Chunk>> pending = new ArrayList<>();
        final List<Long> pendingKeys = new ArrayList<>();
        int asyncCalls, syncCalls, generatedThisTick, maxGeneratedPerTick;
        long syncCostNanos;
        boolean completeAtOnce;
        /** Spigot-like: generating a chunk leaves its eight neighbours half built, and isGenerated says true for them. */
        boolean protoNeighbours;
        final Set<Long> full = new HashSet<>();
        long generatedCheckNanos;

        FakeSource(boolean async, FakeHost host) { this.async = async; this.host = host; }

        Chunk chunk(World world, int x, int z) {
            Chunk chunk = mock(Chunk.class);
            when(chunk.getX()).thenReturn(x);
            when(chunk.getZ()).thenReturn(z);
            when(chunk.getWorld()).thenReturn(world);
            return chunk;
        }

        @Override public boolean asyncAvailable() { return async; }
        @Override public boolean isLoaded(World world, int x, int z) { return loaded.contains(key(x, z)); }
        @Override public boolean isGenerated(World world, int x, int z) { host.now += generatedCheckNanos; return generated.contains(key(x, z)) || loaded.contains(key(x, z)); }
        @Override public Chunk loaded(World world, int x, int z) { return chunk(world, x, z); }
        @Override public CompletableFuture<Chunk> loadAsync(World world, int x, int z, boolean generate) {
            asyncCalls++;
            CompletableFuture<Chunk> future = new CompletableFuture<>();
            boolean exists = isGenerated(world, x, z);
            if (completeAtOnce) {
                if (exists || generate) { loaded.add(key(x, z)); future.complete(chunk(world, x, z)); }
                else future.complete(null);
            } else { pending.add(future); pendingKeys.add(key(x, z)); }
            return future;
        }
        @Override public Chunk loadSync(World world, int x, int z) {
            syncCalls++;
            if (protoNeighbours ? !full.contains(key(x, z)) : !isGenerated(world, x, z)) generatedThisTick++;
            if (protoNeighbours) { full.add(key(x, z)); for (int dx = -1; dx <= 1; dx++) for (int dz = -1; dz <= 1; dz++) generated.add(key(x + dx, z + dz)); }
            maxGeneratedPerTick = Math.max(maxGeneratedPerTick, generatedThisTick);
            host.now += syncCostNanos;
            loaded.add(key(x, z));
            generated.add(key(x, z));
            return chunk(world, x, z);
        }
        @Override public void addTicket(Chunk chunk, Plugin plugin) { ticketsAdded.merge(key(chunk.getX(), chunk.getZ()), 1, Integer::sum); }
        @Override public void removeTicket(World world, int x, int z, Plugin plugin) { ticketsRemoved.merge(key(x, z), 1, Integer::sum); }

        void completeAll(World world) {
            for (int i = 0; i < pending.size(); i++) {
                long k = pendingKeys.get(i);
                loaded.add(k);
                pending.get(i).complete(chunk(world, (int) (k >> 32), (int) k));
            }
            pending.clear();
            pendingKeys.clear();
        }

        int tickets(int x, int z) { return ticketsAdded.getOrDefault(key(x, z), 0) - ticketsRemoved.getOrDefault(key(x, z), 0); }
    }

    static final class FakeHost implements TicketChunkLoads.Host {
        boolean serverThread = true, stopping;
        long now;
        final List<Runnable> hops = new ArrayList<>();
        @Override public boolean serverThread() { return serverThread; }
        @Override public void runOnServer(Runnable task) { hops.add(task); }
        @Override public boolean stopping() { return stopping; }
        @Override public long nanos() { return now; }
        void runHops() { boolean was = serverThread; serverThread = true; List<Runnable> copy = new ArrayList<>(hops); hops.clear(); copy.forEach(Runnable::run); serverThread = was; }
    }

    private final World world = mock(World.class);
    private final Plugin plugin = mock(Plugin.class);
    private final FakeHost host = new FakeHost();

    TicketChunkLoadsTest() {
        when(world.getUID()).thenReturn(UUID.randomUUID());
        when(world.getName()).thenReturn("w");
        when(plugin.getName()).thenReturn("EditPlugin");
        when(plugin.isEnabled()).thenReturn(true);
    }

    private void tick(TicketChunkLoads loads, FakeSource source) { source.generatedThisTick = 0; loads.tick(); host.runHops(); }

    @Test
    void givenHundredRequestsAndEightPerTick_whenTicked_thenEightStartPerTickAndAllWithinThirteenTicks() {
        FakeSource source = new FakeSource(true, host);
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        assertEquals(8, loads.requestsPerTick(), "default from the measurements");
        List<CompletableFuture<ChunkHold>> futures = new ArrayList<>();
        for (int i = 0; i < 100; i++) futures.add(loads.load(plugin, world, i, 0, true));
        assertEquals(100, loads.waiting());
        tick(loads, source);
        assertEquals(8, source.asyncCalls);
        assertEquals(92, loads.waiting());
        for (int t = 2; t <= 12; t++) tick(loads, source);
        assertEquals(96, source.asyncCalls);
        tick(loads, source);
        assertEquals(100, source.asyncCalls);
        assertEquals(0, loads.waiting());
        assertEquals(0, source.syncCalls, "no synchronous load where the async API exists");
        source.completeAll(world);
        host.runHops();
        for (CompletableFuture<ChunkHold> f : futures) assertTrue(f.isDone() && !f.isCompletedExceptionally());
        assertTrue(loads.asynchronous());
    }

    @Test
    void givenLoadedChunkOnTheServerThread_whenLoaded_thenItCompletesAtOnceWithoutARequest() {
        FakeSource source = new FakeSource(true, host);
        source.loaded.add(key(3, -2));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        CompletableFuture<ChunkHold> future = loads.load(plugin, world, 3, -2, true);
        assertTrue(future.isDone());
        ChunkHold hold = future.join();
        assertEquals(3, hold.chunkX());
        assertEquals(-2, hold.chunkZ());
        assertSame(world, hold.world());
        assertEquals(0, source.asyncCalls);
        assertEquals(1, source.tickets(3, -2));
        hold.close();
        assertEquals(0, source.tickets(3, -2));
    }

    @Test
    void givenCompletedLoads_whenClosedOnceOrTwice_thenEachChunkGotOneTicketAndLostItOnce() {
        FakeSource source = new FakeSource(true, host);
        source.completeAtOnce = true;
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        List<CompletableFuture<ChunkHold>> futures = new ArrayList<>();
        for (int i = 0; i < 5; i++) futures.add(loads.load(plugin, world, i, 7, true));
        tick(loads, source);
        for (int i = 0; i < 5; i++) {
            assertEquals(1, source.ticketsAdded.get(key(i, 7)), "one ticket per completion");
            ChunkHold hold = futures.get(i).join();
            hold.close();
            hold.close();
            assertEquals(1, source.ticketsRemoved.get(key(i, 7)), "close twice removes once");
        }
    }

    @Test
    void givenTwoHoldsOfOneChunk_whenTheFirstCloses_thenTheTicketStaysUntilTheSecondCloses() {
        FakeSource source = new FakeSource(true, host);
        source.loaded.add(key(1, 1));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        ChunkHold first = loads.load(plugin, world, 1, 1, true).join();
        ChunkHold second = loads.load(plugin, world, 1, 1, true).join();
        assertEquals(1, source.ticketsAdded.get(key(1, 1)));
        first.close();
        assertEquals(1, source.tickets(1, 1));
        second.close();
        assertEquals(0, source.tickets(1, 1));
    }

    @Test
    void givenCloseOffTheServerThread_whenClosed_thenTheTicketIsRemovedOnTheServerThread() {
        FakeSource source = new FakeSource(true, host);
        source.loaded.add(key(0, 0));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        ChunkHold hold = loads.load(plugin, world, 0, 0, true).join();
        host.serverThread = false;
        hold.close();
        assertEquals(1, source.tickets(0, 0), "not removed off the server thread");
        assertEquals(1, host.hops.size());
        host.runHops();
        assertEquals(0, source.tickets(0, 0));
        assertThrows(IllegalStateException.class, hold::chunk, "chunk() is server thread only");
    }

    @Test
    void givenRequestOffTheServerThreadForALoadedChunk_whenTicked_thenItCompletesWithoutUsingTheBudget() {
        FakeSource source = new FakeSource(true, host);
        for (int i = 0; i < 20; i++) source.loaded.add(key(i, 0));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        host.serverThread = false;
        List<CompletableFuture<ChunkHold>> futures = new ArrayList<>();
        for (int i = 0; i < 20; i++) futures.add(loads.load(plugin, world, i, 0, true));
        assertFalse(futures.get(0).isDone());
        host.serverThread = true;
        tick(loads, source);
        assertEquals(0, source.asyncCalls);
        for (CompletableFuture<ChunkHold> f : futures) assertTrue(f.isDone() && !f.isCompletedExceptionally());
    }

    @Test
    void givenServerStopping_whenTicked_thenWaitingFuturesFailWithCancellation() {
        FakeSource source = new FakeSource(true, host);
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        List<CompletableFuture<ChunkHold>> futures = new ArrayList<>();
        for (int i = 0; i < 20; i++) futures.add(loads.load(plugin, world, i, 0, true));
        tick(loads, source);
        host.stopping = true;
        tick(loads, source);
        for (int i = 8; i < 20; i++) {
            CompletableFuture<ChunkHold> f = futures.get(i);
            assertTrue(f.isCompletedExceptionally());
            assertThrows(CancellationException.class, f::join);
        }
        // the eight in flight finish after the stop flag: no ticket is added, they fail too
        source.completeAll(world);
        host.runHops();
        for (int i = 0; i < 8; i++) assertThrows(CancellationException.class, futures.get(i)::join);
        assertTrue(source.ticketsAdded.isEmpty());
        assertEquals(0, loads.waiting());
    }

    @Test
    void givenSpigotLoaderOfFourMsPerChunkAndFiveMsSlice_whenTicked_thenTwoChunksPerTick() {
        FakeSource source = new FakeSource(false, host);
        source.syncCostNanos = 4_000_000L;
        for (int i = 0; i < 10; i++) source.generated.add(key(i, 0));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        assertEquals(5.0, loads.syncMillisPerTick(), "default from the measurements");
        assertFalse(loads.asynchronous());
        for (int i = 0; i < 10; i++) loads.load(plugin, world, i, 0, true);
        tick(loads, source);
        assertEquals(2, source.syncCalls);
        tick(loads, source);
        assertEquals(4, source.syncCalls);
        assertEquals(0, source.asyncCalls);
    }

    @Test
    void givenSpigotAndChunksThatDoNotExist_whenTicked_thenAtMostOneIsGeneratedPerTickWhileDiskLoadsGoOn() {
        FakeSource source = new FakeSource(false, host);
        source.syncCostNanos = 100_000L;
        for (int i = 0; i < 6; i++) source.generated.add(key(i, 1));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        List<CompletableFuture<ChunkHold>> fresh = new ArrayList<>();
        for (int i = 0; i < 6; i++) {
            fresh.add(loads.load(plugin, world, i, 100, true)); // never generated
            loads.load(plugin, world, i, 1, true);              // on disk
        }
        tick(loads, source);
        assertEquals(1, source.maxGeneratedPerTick);
        assertEquals(7, source.syncCalls, "six from disk and one generated in the first tick");
        for (int t = 0; t < 5; t++) tick(loads, source);
        assertEquals(1, source.maxGeneratedPerTick, "never more than one generated chunk per tick");
        for (CompletableFuture<ChunkHold> f : fresh) assertTrue(f.isDone() && !f.isCompletedExceptionally());
    }

    @Test
    void givenSpigotWhereNeighboursBecomeHalfBuilt_whenSixtyFourNewChunksAreAsked_thenStillOneGenerationPerTick() {
        for (boolean onServerThread : new boolean[]{true, false}) {
            FakeHost host = new FakeHost();
            FakeSource source = new FakeSource(false, host);
            source.protoNeighbours = true;
            source.syncCostNanos = 100_000L;
            TicketChunkLoads loads = new TicketChunkLoads(source, host);
            host.serverThread = onServerThread;
            for (int k = 0; k < 64; k++) loads.load(plugin, world, 400 + k % 8, 400 + k / 8, true);
            host.serverThread = true;
            for (int t = 0; t < 70 && source.syncCalls < 64; t++) { source.generatedThisTick = 0; loads.tick(); host.runHops(); }
            assertEquals(64, source.syncCalls, "all loaded, asked on the server thread: " + onServerThread);
            assertEquals(1, source.maxGeneratedPerTick, "one generation per tick, asked on the server thread: " + onServerThread);
        }
    }

    @Test
    void givenSpigotWhereTheGenerationCheckIsSlow_whenSixtyFourNewChunksAreAskedOffTheServerThread_thenStillOneGenerationPerTick() {
        FakeSource source = new FakeSource(false, host);
        source.protoNeighbours = true;
        source.syncCostNanos = 100_000L;
        source.generatedCheckNanos = 3_000_000L; // only one request can be judged before the first load of a tick
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        host.serverThread = false;
        for (int k = 0; k < 64; k++) loads.load(plugin, world, 400 + k % 8, 400 + k / 8, true);
        host.serverThread = true;
        for (int t = 0; t < 200 && source.syncCalls < 64; t++) { source.generatedThisTick = 0; loads.tick(); host.runHops(); }
        assertEquals(64, source.syncCalls);
        assertEquals(1, source.maxGeneratedPerTick);
    }

    @Test
    void givenGenerateFalseAndAChunkThatDoesNotExist_whenLoaded_thenTheFutureFailsAndNothingIsGenerated() {
        FakeSource spigot = new FakeSource(false, host);
        TicketChunkLoads sync = new TicketChunkLoads(spigot, host);
        CompletableFuture<ChunkHold> a = sync.load(plugin, world, 50, 50, false);
        tick(sync, spigot);
        CompletionException failed = assertThrows(CompletionException.class, a::join);
        assertInstanceOf(NoSuchElementException.class, failed.getCause());
        assertEquals(0, spigot.syncCalls);

        FakeSource paper = new FakeSource(true, host);
        paper.completeAtOnce = true;
        TicketChunkLoads async = new TicketChunkLoads(paper, host);
        CompletableFuture<ChunkHold> b = async.load(plugin, world, 50, 50, false);
        tick(async, paper);
        failed = assertThrows(CompletionException.class, b::join);
        assertInstanceOf(NoSuchElementException.class, failed.getCause());
        assertTrue(paper.ticketsAdded.isEmpty());
    }

    @Test
    void givenPluginDisabled_whenReleased_thenItsWaitingLoadsFailAndItsTicketsAreRemoved() {
        FakeSource source = new FakeSource(true, host);
        source.loaded.add(key(9, 9));
        TicketChunkLoads loads = new TicketChunkLoads(source, host);
        ChunkHold held = loads.load(plugin, world, 9, 9, true).join();
        CompletableFuture<ChunkHold> waiting = loads.load(plugin, world, 10, 9, true);
        loads.release(plugin);
        assertThrows(CancellationException.class, waiting::join);
        assertEquals(0, source.tickets(9, 9));
        held.close();
        assertEquals(1, source.ticketsRemoved.get(key(9, 9)), "a later close removes nothing more");
        assertEquals(0, loads.waiting());
    }

    @Test
    void givenBudgetSetters_whenOutOfRange_thenClamped() {
        TicketChunkLoads loads = new TicketChunkLoads(new FakeSource(true, host), host);
        loads.requestsPerTick(0);
        assertEquals(1, loads.requestsPerTick());
        loads.requestsPerTick(10_000);
        assertEquals(256, loads.requestsPerTick());
        loads.syncMillisPerTick(0.01);
        assertEquals(0.5, loads.syncMillisPerTick());
        loads.syncMillisPerTick(500);
        assertEquals(50.0, loads.syncMillisPerTick());
    }
}
