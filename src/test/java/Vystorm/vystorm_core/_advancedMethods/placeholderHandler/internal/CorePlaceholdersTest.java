    // ------------------------------------------------------------------ the list in docs/API.md

    /**
     * The table of Core's placeholders in docs/API.md is this output. After changing a value or its English
     * description, write the new table with
     * {@code VYSTORM_PLACEHOLDER_DOC_OUT=<file> ./gradlew test --tests '*CorePlaceholdersTest*' --no-daemon}
     * and paste it between the two marker lines.
     */
    @Test
    void givenDeclaredValues_whenDocsRead_thenTheGeneratedListIsInApiMd() throws Exception {
        YamlConfiguration english = language("en");
        List<String> rows = new ArrayList<>();
        rows.add("| Placeholder | Short form | What it shows | Thread |");
        rows.add("| --- | --- | --- | --- |");
        for (String name : CorePlaceholders.NAMESPACES)
            for (PlaceholderValue value : placeholders.namespace(name).orElseThrow().values())
                rows.add("| `" + PlaceholdersAdmin.percent(name, value) + "` | `" + PlaceholdersAdmin.brace(name, value) + "` | "
                        + english.getString("placeholders.values." + name + "." + value.key()) + " | "
                        + (value.isAsyncSafe() ? "any" : "server") + " |");
        String table = String.join("\n", rows);
        String out = System.getenv("VYSTORM_PLACEHOLDER_DOC_OUT");
        if (out != null && !out.isBlank()) {
            Files.writeString(Path.of(out), table + "\n", StandardCharsets.UTF_8);
            return;
        }
        String docs = Files.readString(Path.of("docs/API.md"), StandardCharsets.UTF_8).replace("\r\n", "\n");
        int begin = docs.indexOf(DOC_BEGIN), end = docs.indexOf(DOC_END);
        assertTrue(begin >= 0 && end > begin, "docs/API.md needs the lines " + DOC_BEGIN + " and " + DOC_END);
        assertEquals(table, docs.substring(begin + DOC_BEGIN.length(), end).strip(),
                "docs/API.md: the list of Core's placeholders is out of date (see the Javadoc of this test)");
    }
